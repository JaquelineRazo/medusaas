"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { inputClass, submitClass } from "@/components/AuthCard";
import { createClient } from "@/lib/supabase/browser";

export function MfaForm({ enrolled }: { enrolled: boolean }) {
  const router = useRouter();
  const [factorId, setFactorId] = useState<string | null>(null);
  const [qr, setQr] = useState<string | null>(null);
  const [secret, setSecret] = useState<string | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);

  useEffect(() => {
    const supabase = createClient();
    (async () => {
      const { data } = await supabase.auth.mfa.listFactors();
      const verified = data?.totp.find((f) => f.status === "verified");
      if (verified) {
        setFactorId(verified.id);
        return;
      }
      // Clear half-finished enrolments before starting a new one.
      for (const f of data?.all ?? []) if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      const { data: created, error: e } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "meduSAAS" });
      if (e || !created) return setError(e?.message ?? "Couldn't start the setup. Reload the page.");
      setFactorId(created.id);
      setQr(created.totp.qr_code);
      setSecret(created.totp.secret);
    })();
  }, []);

  async function verify(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setPending(true);
    setError(null);
    const { error: err } = await createClient().auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setPending(false);
    if (err) return setError("That code didn't work. Wait for a new one and try again.");
    router.replace("/console");
    router.refresh();
  }

  return (
    <form onSubmit={verify} className="mt-6 space-y-4">
      {!enrolled && (
        <div className="flex flex-col items-center gap-3 rounded-2xl bg-white p-4">
          {qr ? (
            // eslint-disable-next-line @next/next/no-img-element -- data URI generated by Supabase
            <img src={qr} alt="QR code to add meduSAAS to your authenticator app" width={180} height={180} />
          ) : (
            <span className="grid h-[180px] w-[180px] place-items-center text-sm text-muted">Preparing…</span>
          )}
          {secret && (
            <p className="text-center text-xs text-muted">
              Can&apos;t scan it? Enter this key: <code className="font-mono break-all text-ink">{secret}</code>
            </p>
          )}
        </div>
      )}
      <label className="block text-sm">
        <span className="font-medium">6-digit code</span>
        <input
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="[0-9]{6}"
          maxLength={6}
          required
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
          className={`${inputClass} text-center font-mono text-lg tracking-[0.4em]`}
        />
      </label>
      {error && (
        <p role="alert" className="text-sm text-danger">
          {error}
        </p>
      )}
      <button type="submit" disabled={pending || !factorId} className={submitClass}>
        {pending ? "Checking…" : "Verify"}
      </button>
    </form>
  );
}
